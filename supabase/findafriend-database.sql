-- ============================================================
-- GENERIC UPDATED_AT TRIGGER
-- ============================================================

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ============================================================
-- PROFILES
-- ============================================================

create table if not exists public.profiles (
  id uuid primary key
    references auth.users(id)
    on delete cascade,

  first_name text not null default '',

  birth_date date,

  gender text,

  city text,

  state text,

  about_me text,

  interests_text text,

  is_active boolean not null default true,

  is_banned boolean not null default false,

  created_at timestamptz not null default now(),

  updated_at timestamptz not null default now()
);

create index if not exists profiles_active_idx
on public.profiles (is_active, is_banned);

create index if not exists profiles_created_idx
on public.profiles (created_at desc);

drop trigger if exists profiles_updated_at
on public.profiles;

create trigger profiles_updated_at
before update on public.profiles
for each row
execute function public.set_updated_at();

-- ============================================================
-- AUTOMATIC PROFILE CREATION AFTER SIGNUP
-- ============================================================

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (
    id,
    first_name
  )
  values (
    new.id,
    coalesce(
      new.raw_user_meta_data ->> 'first_name',
      ''
    )
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created
on auth.users;

create trigger on_auth_user_created
after insert on auth.users
for each row
execute function public.handle_new_user();

