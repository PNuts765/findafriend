-- ============================================================
-- LIKES
-- ============================================================

create table if not exists public.likes (
  id bigint generated by default as identity primary key,

  from_user_id uuid not null
    references public.profiles(id)
    on delete cascade,

  to_user_id uuid not null
    references public.profiles(id)
    on delete cascade,

  created_at timestamptz not null default now(),

  constraint likes_not_self
    check (from_user_id <> to_user_id),

  constraint likes_unique_pair
    unique (from_user_id, to_user_id)
);

create index if not exists likes_from_user_idx
on public.likes (from_user_id, created_at desc);

create index if not exists likes_to_user_idx
on public.likes (to_user_id, created_at desc);

-- ============================================================
-- CONVERSATIONS
-- ============================================================

create table if not exists public.conversations (
  id uuid primary key default gen_random_uuid(),

  user_one_id uuid not null
    references public.profiles(id)
    on delete cascade,

  user_two_id uuid not null
    references public.profiles(id)
    on delete cascade,

  created_at timestamptz not null default now(),

  updated_at timestamptz not null default now(),

  constraint conversations_not_self
    check (user_one_id <> user_two_id),

  constraint conversations_unique_pair
    unique (user_one_id, user_two_id)
);

create index if not exists conversations_user_one_idx
on public.conversations (user_one_id, updated_at desc);

create index if not exists conversations_user_two_idx
on public.conversations (user_two_id, updated_at desc);

drop trigger if exists conversations_updated_at
on public.conversations;

